SELECT D.NAME AS DEPARTMENT,E.NAME AS EMPLOYEE,E.SALARY AS SALARY
FROM 
(
    SELECT 
        NAME,
        SALARY,
        DEPARTMENTID,
        DENSE_RANK() OVER(
            PARTITION BY DEPARTMENTID
            ORDER BY SALARY DESC
        ) AS RN
    FROM EMPLOYEE
) E
JOIN DEPARTMENT D
ON E.DEPARTMENTID = D.ID
WHERE E.RN <= 3